"""Generate working Pocket Editor plugins without overwriting existing files."""
import keyword
from pathlib import Path
import re
import tkinter as tk
from tkinter import messagebox, ttk

PLUGIN_DIR = Path(__file__).resolve().parent
DOC_PATH = PLUGIN_DIR.parent / 'PLUGIN_DEVELOPMENT.md'
TEMPLATES = ('Simple command', 'Text transform', 'Tool window', 'Events and services')


def build_source(plugin_id, label, description, template):
    """Validate fields and return Python source without executing it."""
    plugin_id, label, description = plugin_id.strip(), label.strip(), description.strip()
    if not re.fullmatch(r'[a-z][a-z0-9_]{0,63}', plugin_id) or keyword.iskeyword(plugin_id):
        raise ValueError('Plugin ID: use 1–64 lowercase letters, numbers, or underscores; start with a letter and avoid Python keywords.')
    if not label or len(label) > 100 or any(ord(char) < 32 for char in label):
        raise ValueError('Enter a command label of 1–100 characters, without line breaks.')
    if len(description) > 2000:
        raise ValueError('Keep the description within 2,000 characters.')
    if template not in TEMPLATES:
        raise ValueError('Choose a template from the list.')
    header = f'{description or label!r}\n# Generated by Pocket Editor → Plugin Builder.\n# See PLUGIN_DEVELOPMENT.md beside pocket_editor.py.\n'
    if template == 'Simple command':
        body = f'''from tkinter import messagebox


def register(api):
    def run():
        # Read the selected tab when the command runs.
        path = api.get_path()
        name = path.name if path else "Untitled"
        count = len(api.get_text().split())
        messagebox.showinfo({label!r}, f"{{name}}: {{count:,}} words")

    api.add_command({label!r}, run)
'''
    elif template == 'Text transform':
        body = f'''def transform(text):
    """Edit this function to implement your transformation."""
    return text.upper()


def register(api):
    def run():
        # This changes the active tab, supports Undo, and does not save to disk.
        api.replace_text(transform(api.get_text()))

    api.add_command({label!r}, run)
'''
    elif template == 'Tool window':
        body = f'''import tkinter as tk
from tkinter import ttk


def register(api):
    # Advanced GUI access uses the editor's internal integration interface.
    root = api._editor.root
    window = None

    def close():
        nonlocal window
        if window is not None and window.winfo_exists():
            window.destroy()
        window = None

    def run():
        nonlocal window
        if window is not None and window.winfo_exists():
            window.lift()
            return
        window = tk.Toplevel(root)
        window.title({label!r})
        window.transient(root)
        window.protocol("WM_DELETE_WINDOW", close)
        body = ttk.Frame(window, padding=18)
        body.pack(fill="both", expand=True)
        ttk.Label(body, text={description or label!r}, wraplength=420).pack(anchor="w")
        ttk.Button(body, text="Close", command=close).pack(anchor="e", pady=(16, 0))
        window.bind("<Escape>", lambda event: close())

    api.on_cleanup(close)
    api.add_command({label!r}, run)
'''
    else:
        body = f'''from tkinter import messagebox


def register(api):
    def word_count():
        return len(api.get_text().split())

    def saved(source, path, **payload):
        # Use this plugin's own event name to avoid event feedback loops.
        api.emit({plugin_id + '.observed_save'!r}, path=path)

    def run():
        count = word_count()
        api.emit({plugin_id + '.counted'!r}, count=count)
        messagebox.showinfo({label!r}, f"{{count:,}} words")

    api.on("document_saved", saved)
    api.provide_service("word_count", word_count)
    # Other plugins can call api.call_service({plugin_id + '.word_count'!r}).
    api.add_command({label!r}, run)
'''
    source = header + body
    compile(source, plugin_id + '.py', 'exec')
    return source


def create_plugin(folder, plugin_id, label, description, template):
    source = build_source(plugin_id, label, description, template)
    path = Path(folder) / (plugin_id.strip() + '.py')
    # Exclusive creation protects installed plugins, including symlink targets.
    with path.open('x', encoding='utf-8', newline='\n') as stream:
        stream.write(source)
    return path


def register(api):
    editor = api._editor
    window = None

    def close():
        nonlocal window
        if window is not None and window.winfo_exists():
            window.destroy()
        window = None

    def show():
        nonlocal window
        if window is not None and window.winfo_exists():
            window.lift()
            return
        window = tk.Toplevel(editor.root)
        window.title('Plugin Builder')
        window.transient(editor.root)
        window.geometry('820x680')
        window.minsize(560, 460)
        window.protocol('WM_DELETE_WINDOW', close)
        body = ttk.Frame(window, padding=16)
        body.pack(fill='both', expand=True)
        ttk.Label(body, text='Build a Pocket Editor plugin', style='Title.TLabel').pack(anchor='w')
        ttk.Label(body, text='Choose a template, preview the code, then create and load it.',
                  style='Muted.TLabel').pack(anchor='w', pady=(4, 12))
        fields = ttk.Frame(body)
        fields.pack(fill='x')
        fields.columnconfigure(1, weight=1)
        values = [tk.StringVar(window, value) for value in ('my_plugin', 'My Plugin', '', TEMPLATES[0])]
        for row, (label, variable) in enumerate(zip(('Plugin ID', 'Command label', 'Description', 'Template'), values)):
            ttk.Label(fields, text=label).grid(row=row, column=0, sticky='w', padx=(0, 12), pady=4)
            widget = (ttk.Combobox(fields, textvariable=variable, values=TEMPLATES, state='readonly')
                      if row == 3 else ttk.Entry(fields, textvariable=variable))
            widget.grid(row=row, column=1, sticky='ew', pady=4)
        notebook = ttk.Notebook(body)
        notebook.pack(fill='both', expand=True, pady=12)

        def text_page(title):
            frame = ttk.Frame(notebook)
            notebook.add(frame, text=title)
            text = tk.Text(frame, wrap='word', font=editor.editor_font, background='#1e1e1e',
                           foreground='#cccccc', selectbackground='#264f78', borderwidth=0,
                           padx=12, pady=10, width=1, height=1)
            scrollbar = ttk.Scrollbar(frame, command=text.yview)
            text.configure(yscrollcommand=scrollbar.set)
            scrollbar.pack(side='right', fill='y')
            text.pack(fill='both', expand=True)
            return text

        preview = text_page('Code preview')
        docs = text_page('Documentation')
        communication = text_page('Plugin communication')

        def refresh_communication():
            communication.configure(state='normal')
            communication.delete('1.0', 'end')
            communication.insert('1.0', 'LOADED PLUGINS\n' + '\n'.join(api.list_plugins()) +
                                 '\n\nAVAILABLE SERVICES\n' + '\n'.join(api.list_services()) +
                                 '\n\nCall a service: api.call_service("plugin_id.service", ...)'
                                 '\nListen for an event: api.on("plugin_id.event", callback)'
                                 '\nSend an event: api.emit("plugin_id.event", value=123)'
                                 '\n\nUse the Events and services template and the two-plugin example in Documentation.')
            communication.configure(state='disabled')

        refresh_communication()
        try:
            documentation = DOC_PATH.read_text(encoding='utf-8')
        except OSError as error:
            documentation = f'Documentation unavailable: {error}\nExpected file: {DOC_PATH}'
        docs.insert('1.0', documentation)
        docs.configure(state='disabled')
        status = ttk.Label(body, style='Muted.TLabel', wraplength=720)
        status.pack(fill='x', pady=(0, 8))
        buttons = ttk.Frame(body)
        buttons.pack(fill='x')

        def update_preview(*args):
            try:
                source = build_source(*(value.get() for value in values))
                status.configure(text=f'Creates {PLUGIN_DIR / (values[0].get().strip() + ".py")}')
            except ValueError as error:
                source = '# ' + str(error)
                status.configure(text=str(error))
            preview.configure(state='normal')
            preview.delete('1.0', 'end')
            preview.insert('1.0', source)
            preview.configure(state='disabled')

        def create():
            try:
                path = create_plugin(PLUGIN_DIR, *(value.get() for value in values))
            except (OSError, ValueError, SyntaxError) as error:
                messagebox.showerror('Plugin Builder', str(error), parent=window)
                return
            editor.load_plugins()
            refresh_communication()
            editor.open_path(path)
            if path in editor.loaded_plugins:
                status.configure(text=f'Created and loaded {path.name}. Run it from Extensions. Restart the editor after editing a loaded plugin.')
            else:
                status.configure(text=f'Created {path.name}, but loading failed. Check the plugin error and restart after fixing it.')
            window.lift()

        ttk.Button(buttons, text='Refresh services', command=refresh_communication).pack(side='left', padx=(0, 8))
        ttk.Button(buttons, text='Open documentation in editor',
                   command=lambda: editor.open_path(DOC_PATH)).pack(side='left')
        ttk.Button(buttons, text='Create & load', command=create, style='Accent.TButton').pack(side='right')
        for variable in values:
            variable.trace_add('write', update_preview)
        update_preview()
        window.bind('<Escape>', lambda event: close())

    api.add_command('Plugin Builder…', show)
    api.on_cleanup(close)
